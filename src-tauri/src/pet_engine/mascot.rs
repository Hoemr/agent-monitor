//! Mascot host: bridges the [`PetBackend`] contract to the real pet window.
//!
//! The ticker thread (spawned in `lib.rs`) owns nothing but timing: every
//! tick it asks the [`MascotHost`] for the next [`PetFrame`], applies the
//! backend's window policy (roaming anchor or fixed window), and emits
//! `pet-frame` for the webview's thin blit layer. Packs are discovered by
//! shape — `conf/actions.xml` means Shimeji, `pack.json` means a state pack —
//! so new pet kinds register by adding a loader, not by touching the host.

use super::backend::{BackendInfo, MenuAction, PetBackend, PetFrame, WindowPolicy};
use super::behavior::{ensure_required_behaviors, Mood, SpriteBackend, World};
use super::pack::{load_pack, load_pack_dir, Pack, PackError, PackFiles, PackSource};
use crate::pet_engine::state::{load_state_pack, load_state_pack_cached, StateBackend};
use std::collections::BTreeMap;
use std::path::PathBuf;
use std::sync::{Mutex, OnceLock};

// ── Pack discovery ───────────────────────────────────────────────────

macro_rules! builtin_frames {
    ($dir:literal, $($file:literal),* $(,)?) => {{
        let mut files = PackFiles::new();
        files.insert(
            "conf/actions.xml".into(),
            include_bytes!(concat!("../../pets/", $dir, "/conf/actions.xml")).to_vec(),
        );
        files.insert(
            "conf/behaviors.xml".into(),
            include_bytes!(concat!("../../pets/", $dir, "/conf/behaviors.xml")).to_vec(),
        );
        $( files.insert(concat!("img/", $file).into(), include_bytes!(concat!("../../pets/", $dir, "/img/", $file)).to_vec()); )*
        files
    }};
}

/// The Shimeji packs compiled into the binary (generated by
/// `scripts/make-pets.py`).
pub fn builtin_pack_files() -> Vec<(&'static str, PackFiles)> {
    vec![
        (
            "agent-cat",
            builtin_frames!(
                "agent-cat", "shime1.png", "shime2.png", "shime3.png", "shime4.png",
                "shime5.png", "shime6.png", "shime7.png", "shime8.png"
            ),
        ),
        (
            "byte-slime",
            builtin_frames!(
                "byte-slime", "shime1.png", "shime2.png", "shime3.png", "shime4.png",
                "shime5.png", "shime6.png", "shime7.png", "shime8.png"
            ),
        ),
    ]
}

fn cache() -> &'static Mutex<BTreeMap<String, Pack>> {
    static CACHE: OnceLock<Mutex<BTreeMap<String, Pack>>> = OnceLock::new();
    CACHE.get_or_init(|| Mutex::new(BTreeMap::new()))
}

/// Directory a custom pack lives in.
pub fn pack_dir(name: &str) -> Option<PathBuf> {
    super::pack::pets_dir().map(|d| d.join(name))
}

fn is_builtin_shimeji(name: &str) -> bool {
    builtin_pack_files().iter().any(|(n, _)| *n == name)
}

fn is_builtin_state(name: &str) -> bool {
    crate::pet_engine::state::builtin_state_pack_files().iter().any(|(n, _)| *n == name)
}

fn load_shimeji_uncached(name: &str) -> Result<Pack, PackError> {
    for (builtin, files) in builtin_pack_files() {
        if builtin == name {
            let mut pack = load_pack(name, &files, PackSource::Embedded)?;
            ensure_required_behaviors(&mut pack);
            return Ok(pack);
        }
    }
    let dir = pack_dir(name).ok_or(PackError::MissingActions)?;
    let mut pack = load_pack_dir(&dir)?;
    ensure_required_behaviors(&mut pack);
    Ok(pack)
}

/// Load a Shimeji pack by name, caching the parsed result.
pub fn load_pack_cached(name: &str) -> Result<Pack, PackError> {
    if let Ok(cache) = cache().lock() {
        if let Some(hit) = cache.get(name) {
            return Ok(hit.clone());
        }
    }
    let pack = load_shimeji_uncached(name)?;
    if let Ok(mut cache) = cache().lock() {
        cache.insert(name.to_string(), pack.clone());
    }
    Ok(pack)
}

pub fn invalidate_pack(name: &str) {
    if let Ok(mut cache) = cache().lock() {
        cache.remove(name);
    }
    crate::pet_engine::state::invalidate_state_pack(name);
}

/// PNG bytes for an image key: Shimeji packs key frames by `"/shime1.png"`,
/// state packs by state name. The frontend just echoes the frame's key back.
pub fn pack_image(name: &str, key: &str) -> Option<Vec<u8>> {
    if let Ok(pack) = load_pack_cached(name) {
        if let Some(bytes) = pack.images.get(key) {
            return Some(bytes.clone());
        }
    }
    crate::pet_engine::state::state_pack_image(name, key)
}

/// The logical window edge a pack wants: state pets own their size, roaming
/// pets use the user's collapsed size.
pub fn pet_window_size(pack_name: &str, collapsed: f64) -> f64 {
    let _ = pack_name; // state pets follow collapsed size, like the capsule
    collapsed
}

/// All selectable packs as backend descriptions: built-ins first, then every
/// directory under `pets/` that parses. Broken custom packs surface with
/// their error so Settings can show why a pack does not appear.
pub fn list_packs() -> Vec<BackendInfo> {
    let mut out = Vec::new();
    // Legacy pixel packs remain loadable, but the picker offers the new art.
    for (name, files) in crate::pet_engine::state::builtin_state_pack_files() {
        if let Ok(pack) = crate::pet_engine::state::load_state_pack(name, &files.clone()) {
            out.push(StateBackend::new(pack).info());
        }
    }
    if let Some(pets) = super::pack::pets_dir() {
        let mut customs: Vec<String> = std::fs::read_dir(&pets)
            .map(|entries| {
                entries
                    .flatten()
                    .filter(|e| e.path().is_dir())
                    .filter_map(|e| e.file_name().to_string_lossy().to_string().into())
                    .collect()
            })
            .unwrap_or_default();
        customs.sort();
        for name in customs {
            if is_builtin_shimeji(&name) || is_builtin_state(&name) {
                continue; // built-ins are already listed
            }
            let dir = pack_dir(&name);
            let is_state = dir.as_ref().map(|d| d.join("pack.json").exists()).unwrap_or(false);
            let info = if is_state {
                crate::pet_engine::state::load_state_pack_cached(&name)
                    .map(|pack| StateBackend::new(pack).info())
                    .unwrap_or_else(|error| broken_info(&name, vec![error]))
            } else {
                load_pack_cached(&name)
                    .map(|pack| {
                        SpriteBackend {
                            pack,
                            mascot: super::behavior::Mascot::new((0.0, 0.0), 1),
                            builtin: false,
                            mascot_world: World { left: 0.0, right: 0.0, top: 0.0, bottom: 0.0 },
                        }
                        .info()
                    })
                    .unwrap_or_else(|e: PackError| broken_info(&name, vec![e.to_string()]))
            };
            out.push(info);
        }
    }
    out
}

fn broken_info(name: &str, warnings: Vec<String>) -> BackendInfo {
    BackendInfo {
        name: name.to_string(),
        display_name: None,
        kind: "unknown".into(),
        builtin: false,
        author: None,
        license: None,
        source: None,
        frame_size: (0, 0),
        window_size: 0.0,
        warnings,
        menu: Vec::new(),
        actions: Vec::new(),
    }
}

/// One incoming file of an imported pack (relative path inside the pack).
pub struct IncomingFile {
    pub path: String,
    pub bytes: Vec<u8>,
}

/// Validate an uploaded pack in memory, then persist it to `pets/<name>/`.
/// Nothing is written unless the pack parses cleanly. Accepts both kinds:
/// a Shimeji layout (conf/ + img/) or a state layout (pack.json + images).
pub fn import_pack(name: &str, files: &[IncomingFile]) -> Result<BackendInfo, String> {
    let sanitized = sanitize_pack_name(name)?;
    let mut map = PackFiles::new();
    for file in files {
        // The browser sends paths like "<folder>/conf/actions.xml"; keep the
        // part from the first conf/ or img/ component on.
        let rel = normalize_incoming_path(&file.path);
        if rel.split('/').any(|c| c == "..") {
            return Err(format!("非法路径: {}", file.path));
        }
        map.insert(rel, file.bytes.clone());
    }
    let has_state = map.contains_key("pack.json");
    let mut warnings = Vec::new();
    let mut actions = Vec::new();
    let mut menu = Vec::new();
    let mut frame_size = (0u32, 0u32);
    let mut window_size = 0.0f64;
    if has_state {
        let pack = load_state_pack(&sanitized, &map).map_err(|e| e.to_string())?;
        frame_size = pack.frame_size;
        warnings = pack.warnings.clone();
        let backend = StateBackend::new(pack);
        menu = backend.menu_actions();
        actions = menu.iter().map(|m| m.action.clone()).collect();
        window_size = backend.window_size();
    } else {
        let mut pack = load_pack(&sanitized, &map, PackSource::Directory).map_err(|e| e.to_string())?;
        ensure_required_behaviors(&mut pack);
        frame_size = pack.frame_size;
        warnings = pack.warnings.clone();
        let backend = SpriteBackend {
            pack: pack.clone(),
            mascot: super::behavior::Mascot::new((0.0, 0.0), 1),
            builtin: false,
            mascot_world: World { left: 0.0, right: 0.0, top: 0.0, bottom: 0.0 },
        };
        menu = backend.menu_actions();
        actions = menu.iter().map(|m| m.action.clone()).collect();
    }
    let info = BackendInfo {
        name: sanitized.clone(),
        display_name: None,
        kind: if has_state { "state".into() } else { "shimeji".into() },
        builtin: false,
        author: None,
        license: None,
        source: None,
        frame_size,
        window_size,
        warnings,
        menu,
        actions,
    };
    let dir = pack_dir(&sanitized).ok_or("pets 目录不可用")?;
    std::fs::create_dir_all(dir.join("conf")).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(dir.join("img")).map_err(|e| e.to_string())?;
    for (path, bytes) in &map {
        let target = dir.join(path);
        if let Some(parent) = target.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        std::fs::write(target, bytes).map_err(|e| e.to_string())?;
    }
    invalidate_pack(&sanitized);
    Ok(info)
}

fn sanitize_pack_name(name: &str) -> Result<String, String> {
    let trimmed = name.trim();
    if trimmed.is_empty() {
        return Err("宠物包名为空".into());
    }
    let ok = trimmed
        .chars()
        .all(|c| c.is_alphanumeric() || c == '-' || c == '_' || c == ' ');
    if !ok {
        return Err("宠物包名只能包含字母、数字、空格、- 和 _".into());
    }
    Ok(trimmed.to_string())
}

fn normalize_incoming_path(path: &str) -> String {
    let cleaned = path.replace('\\', "/");
    for prefix in ["conf/", "img/"] {
        if let Some(at) = cleaned.find(prefix) {
            return cleaned[at..].to_string();
        }
    }
    cleaned.trim_start_matches('/').to_string()
}

// ── Host state ───────────────────────────────────────────────────────

/// Per-app mascot state held in `Runtime`. Owns the active backend; screen
/// geometry and moods flow in from the window paths.
pub struct MascotHost {
    pub pack_name: String,
    pub backend: Option<Box<dyn PetBackend>>,
    /// `(millis, x, y)` samples of recent user-driven window moves, for the
    /// release velocity of a throw.
    pub drag_history: Vec<(u64, f64, f64)>,
    pub task_mood: super::TaskMoodTracker,
}

impl MascotHost {
    pub fn new(default_pack: &str) -> Self {
        MascotHost {
            pack_name: default_pack.to_string(),
            backend: None,
            drag_history: Vec::new(),
            task_mood: super::TaskMoodTracker::default(),
        }
    }

    pub fn ready(&self) -> bool {
        self.backend.is_some()
    }

    /// Drop the active backend so the next tick re-activates (pack changed
    /// or re-imported on disk).
    pub fn invalidate(&mut self) {
        self.backend = None;
    }

    pub fn window_policy(&self) -> WindowPolicy {
        self.backend
            .as_ref()
            .map(|b| b.window_policy())
            .unwrap_or(WindowPolicy::FollowsAnchor)
    }

    /// The logical window edge to apply: state pets own their size; roaming
    /// pets follow the user's collapsed size.
    pub fn window_size(&self, collapsed: f64) -> f64 {
        match self.window_policy() {
            WindowPolicy::Fixed => self
                .backend
                .as_ref()
                .map(|b| b.window_size())
                .unwrap_or(collapsed),
            WindowPolicy::FollowsAnchor => collapsed,
        }
    }

    /// (Re)load the pack and (re)build the backend at `anchor` if needed.
    /// Returns false when the pack is broken — the caller falls back to the
    /// classic pet rather than showing nothing.
    pub fn activate(&mut self, pack_name: &str, anchor: (f64, f64), seed: u64) -> bool {
        if self.ready() && self.pack_name == pack_name {
            return true;
        }
        match build_backend(pack_name, anchor, seed) {
            Some(backend) => {
                self.backend = Some(backend);
                self.pack_name = pack_name.to_string();
                true
            }
            None => {
                self.backend = None;
                false
            }
        }
    }

    pub fn set_world(&mut self, world: World) {
        if let Some(backend) = &mut self.backend {
            backend.set_world(world);
        }
    }

    pub fn set_mood(&mut self, mood: Mood) {
        if let Some(backend) = &mut self.backend {
            backend.set_mood(mood);
        }
    }

    pub fn tick(&mut self) -> Option<PetFrame> {
        self.backend.as_mut().and_then(|b| b.tick())
    }

    pub fn menu_actions(&self) -> Vec<MenuAction> {
        self.backend
            .as_ref()
            .map(|b| b.menu_actions())
            .unwrap_or_default()
    }

    pub fn perform(&mut self, action: &str) -> bool {
        self.backend
            .as_mut()
            .map(|b| b.perform(action))
            .unwrap_or(false)
    }

    pub fn center(&mut self) {
        if let Some(backend) = &mut self.backend {
            backend.center();
        }
    }

    /// Drag ended at `anchor`; apply the recorded window velocity as a throw
    /// when the user was flinging, else drop in place.
    pub fn drag_ended(&mut self, anchor: (f64, f64), now_ms: u64) {
        let history = std::mem::take(&mut self.drag_history);
        let velocity = Self::release_velocity(&history, now_ms);
        if let Some(backend) = &mut self.backend {
            backend.drag_ended(anchor, velocity);
        }
    }

    /// px per tick (40 ms) estimated from the drag history.
    fn release_velocity(history: &[(u64, f64, f64)], _now_ms: u64) -> (f64, f64) {
        const WINDOW_MS: u64 = 140;
        let Some(&(last_t, lx, ly)) = history.last() else {
            return (0.0, 0.0);
        };
        let reference = history
            .iter()
            .rev()
            .find(|(t, _, _)| last_t.saturating_sub(*t) >= WINDOW_MS)
            .cloned()
            .unwrap_or_else(|| history.first().copied().unwrap_or((last_t, lx, ly)));
        let dt = (last_t - reference.0).max(1) as f64;
        (
            ((lx - reference.1) / dt) * super::behavior::TICK_MS as f64,
            ((ly - reference.2) / dt) * super::behavior::TICK_MS as f64,
        )
    }

    /// The anchor (feet) point for a window rect: horizontal center,
    /// `margin` above the bottom edge.
    pub fn anchor_of(rect: (f64, f64, f64, f64), margin: f64) -> (f64, f64) {
        (rect.0 + rect.2 / 2.0, rect.1 + rect.3 - margin)
    }

    /// Window position (physical px) placing the anchor at the window's
    /// center-x / `margin`-above-bottom.
    pub fn window_pos_for(anchor: (f64, f64), size_phys: f64, margin_phys: f64) -> (i32, i32) {
        (
            (anchor.0 - size_phys / 2.0).round() as i32,
            (anchor.1 - size_phys + margin_phys).round() as i32,
        )
    }

    /// CSS zoom so the pack's largest frame fills the window.
    pub fn zoom_css(size_logical: f64, frame_size: (u32, u32)) -> f64 {
        let largest = frame_size.0.max(frame_size.1).max(1) as f64;
        size_logical / largest
    }
}

/// Build the backend for a pack name by discovering its kind.
fn build_backend(name: &str, anchor: (f64, f64), seed: u64) -> Option<Box<dyn PetBackend>> {
    if let Ok(mut pack) = load_pack_cached(name) {
        ensure_required_behaviors(&mut pack);
        return Some(Box::new(SpriteBackend {
            pack,
            mascot: super::behavior::Mascot::new(anchor, seed),
            builtin: is_builtin_shimeji(name),
            mascot_world: World { left: 0.0, right: 0.0, top: 0.0, bottom: 0.0 },
        }));
    }
    if let Ok(pack) = load_state_pack_cached(name) {
        return Some(Box::new(StateBackend::new(pack)));
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builtin_packs_parse_and_have_frames() {
        for (name, _) in builtin_pack_files() {
            let pack = load_pack_cached(name).expect(name);
            assert_eq!(pack.frame_size, (72, 72), "{name}");
            assert!(pack.actions.contains_key("Walk"), "{name}");
            assert!(pack.behaviors.iter().any(|b| b.name == "Fall"), "{name}");
        }
    }

    #[test]
    fn builtin_state_packs_parse_with_license() {
        for (name, files) in crate::pet_engine::state::builtin_state_pack_files() {
            let pack = crate::pet_engine::state::load_state_pack(name, &files).expect(name);
            assert!(pack.states.contains_key("idle"), "{name}");
            assert!(pack.license.is_some(), "{name} must carry its license");
        }
    }

    #[test]
    fn pack_image_serves_named_frames() {
        assert!(pack_image("agent-cat", "/shime1.png").is_some());
        assert!(pack_image("agent-cat", "/nope.png").is_none());
        assert!(pack_image("missing-pack", "/shime1.png").is_none());
    }

    #[test]
    fn pet_window_size_always_follows_the_collapsed_size() {
        // "The pet is just different artwork": every kind uses the classic
        // window size so snap/sliver/edge-hide behave identically.
        assert_eq!(pet_window_size("agent-cat", 72.0), 72.0);
        assert_eq!(pet_window_size("british-blue", 72.0), 72.0);
        assert_eq!(pet_window_size("no-such-pack", 96.0), 96.0);
    }

    #[test]
    fn list_packs_offers_new_characters_with_complete_states_and_menus() {
        let packs = list_packs();
        assert!(!packs.iter().any(|p| matches!(p.name.as_str(), "agent-cat" | "byte-slime")));
        for name in ["nailong", "doraemon", "tihun"] {
            let info = packs.iter().find(|p| p.name == name).expect(name);
            assert_eq!(info.kind, "state");
            assert!(info.builtin);
            assert!(info.display_name.is_some());
            assert!(info.warnings.is_empty());
            assert!(info.menu.iter().any(|m| m.action == "interact"));
            for state in ["idle", "working", "thinking", "interacting", "celebrating", "alarmed", "sleeping", "watching"] {
                assert!(pack_image(name, state).is_some(), "{name}: {state}");
            }
            let mut host = MascotHost::new(name);
            assert!(host.activate(name, (100.0, 600.0), 7));
            assert_eq!(host.window_policy(), WindowPolicy::Fixed);
            assert!(host.perform("interact"));
        }
        let blue = packs.iter().find(|p| p.name == "british-blue").unwrap();
        assert_eq!(blue.kind, "state");
        assert!(blue.license.is_some());
        assert!(blue.menu.iter().any(|m| m.action == "interact"));
    }

    #[test]
    fn activate_builds_the_right_backend_kind() {
        let mut host = MascotHost::new("agent-cat");
        assert!(host.activate("agent-cat", (100.0, 600.0), 7));
        assert_eq!(host.window_policy(), WindowPolicy::FollowsAnchor);
        assert!(host.perform("Walk"));
        assert!(host.activate("british-blue", (100.0, 600.0), 7));
        assert_eq!(host.window_policy(), WindowPolicy::Fixed);
        assert!(host.perform("interact"));
        assert!(!host.perform("Walk")); // state packs do not walk
    }

    #[test]
    fn import_rejects_bad_names_and_broken_packs_before_writing() {
        assert!(import_pack("../evil", &[IncomingFile {
            path: "conf/actions.xml".into(),
            bytes: b"<Mascot/>".to_vec(),
        }])
        .is_err());
        assert!(import_pack("bad pack!", &[IncomingFile {
            path: "conf/actions.xml".into(),
            bytes: b"<Mascot/>".to_vec(),
        }])
        .is_err());
        let dir = pack_dir("broken-pack");
        let result = import_pack(
            "broken-pack",
            &[IncomingFile {
                path: "conf/actions.xml".into(),
                bytes: b"<?xml version=\"1.0\"?><Mascot xmlns=\"http://www.group-finity.com/Mascot\"><ActionList/></Mascot>".to_vec(),
            }],
        );
        assert!(result.is_err());
        if let Some(dir) = dir {
            assert!(!dir.exists(), "nothing must be written for a failed import");
        }
    }

    #[test]
    fn normalize_incoming_paths_finds_conf_and_img() {
        assert_eq!(normalize_incoming_path("mycat/conf/actions.xml"), "conf/actions.xml");
        assert_eq!(normalize_incoming_path("mycat\\img\\shime1.png"), "img/shime1.png");
        assert_eq!(normalize_incoming_path("conf/actions.xml"), "conf/actions.xml");
    }

    #[test]
    fn drag_ended_applies_history_velocity() {
        let mut host = MascotHost::new("agent-cat");
        host.set_world(World { left: 0.0, right: 1000.0, top: 0.0, bottom: 600.0 });
        assert!(host.activate("agent-cat", (100.0, 600.0), 7));
        host.drag_history = vec![(0, 100.0, 600.0), (150, 340.0, 590.0)];
        host.drag_ended((340.0, 590.0), 160);
        // Ballistic or gentle fall — either way the mascot left the drag.
        assert!(host.ready());
    }
}
